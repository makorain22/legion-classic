#!/usr/bin/env python3
"""Generates engine/src/core/sin_table.inc: a quarter-wave sine table in Q16.16.

The simulation must give identical results on every PC, so it never calls
std::sin at runtime. This table is generated once and checked in.
Angles use 4096 units per full circle; the table covers 0..1024 (0..90 deg).
"""
import math, pathlib
vals = [round(math.sin(i / 4096 * 2 * math.pi) * 65536) for i in range(1025)]
out = pathlib.Path(__file__).resolve().parents[2] / "engine/src/core/sin_table.inc"
lines = ["// Generated by tools/scripts/gen_sin_table.py - do not edit.", "// sin(i * 2pi / 4096) * 65536 for i = 0..1024"]
for i in range(0, 1025, 12):
    lines.append("    " + ", ".join(str(v) for v in vals[i:i+12]) + ",")
out.write_text("\n".join(lines) + "\n")
print("wrote", out)
